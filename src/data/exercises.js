/**
 * Default variation for a given experience level:
 *  beginner → the hardest of the beginner options (e.g. knee push-up)
 *  some / trained → the first standard option
 * The user can always switch easier/harder per exercise.
 */
export function defaultVariationIndex(ex, experience = 'beginner') {
  const v = ex.variations;
  if (experience === 'beginner') {
    let idx = 0;
    v.forEach((x, i) => { if (x.level === 'beginner') idx = i; });
    return idx;
  }
  const std = v.findIndex((x) => x.level === 'standard');
  return std >= 0 ? std : 0;
}
